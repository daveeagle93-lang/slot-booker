// Pure helpers for scripts/configure.ts, kept apart so tests can import them without touching any file.
export interface Account {
  productionDatabaseId: string;
  previewDatabaseId: string;
  /** The Worker's name. Wrangler derives env.preview's from it (`<name>-preview`). */
  name?: string;
  /** Shared by both environments. */
  vars: Record<string, string>;
  /** Added to the production block only, over `vars`. */
  productionVars?: Record<string, string>;
  /** Added to env.preview only, over `vars`. */
  previewVars?: Record<string, string>;
}

/**
 * What to print when account.local.json doesn't parse. Node's JSON.parse message can quote a few characters
 * of the file, which could be a secret put there by mistake, so the message text is never used: only the
 * position number in it is read, and turned into a line and column by counting newlines in `text`
 * (which is not itself printed). With no position (for example "Unexpected end of JSON input") there is none.
 */
export function describeJsonError(error: unknown, text: string): string {
  const base = "account.local.json is not valid JSON";
  const digits = error instanceof Error ? /\bposition (\d+)/.exec(error.message)?.[1] : undefined;
  const position = digits === undefined ? NaN : Number(digits);
  if (!Number.isSafeInteger(position) || position > text.length) return base;
  const before = text.slice(0, position);
  const line = before.split("\n").length;
  const column = position - (before.lastIndexOf("\n") + 1) + 1;
  return `${base} (line ${line}, column ${column})`;
}

/** What to print when account.local.json can't be read: the error's `code` only, never its message. */
export function describeReadError(error: unknown): string {
  const code = typeof error === "object" && error !== null ? (error as { code?: unknown }).code : undefined;
  return typeof code === "string" && /^[A-Z0-9_]{1,32}$/.test(code)
    ? `Couldn't read account.local.json (${code}).`
    : "Couldn't read account.local.json.";
}

export const GENERATED_MARKER = "GENERATED by `npm run configure` from wrangler.jsonc and account.local.json. Git-ignored. Do not edit; `npm run configure -- --clear` removes it.";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// The committed placeholders are ...0000 and ...0001; anything of that all-zero shape is refused.
const PLACEHOLDER = /^0{8}-0{4}-0{4}-0{4}-0{11}[0-9a-f]$/i;
const KEYS = new Set(["productionDatabaseId", "previewDatabaseId", "name", "vars", "productionVars", "previewVars"]);
const VAR_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
// Secrets must go to Worker secrets or .dev.vars: a var is stored and uploaded in plain text.
const SECRET_VARS = new Set(["ADMIN_PASSWORD_HASH", "ADMIN_SESSION_SECRET"]);

function parseVars(key: string, value: unknown, errors: string[]): Record<string, string> {
  const vars: Record<string, string> = {};
  if (value === undefined) return vars;
  if (typeof value !== "object" || value === null || Array.isArray(value)) errors.push(`${key} must be an object of name: string.`);
  else {
    for (const [k, v] of Object.entries(value)) {
      if (!VAR_NAME.test(k)) errors.push(`${key}: "${k}" is not a valid variable name.`);
      else if (SECRET_VARS.has(k)) errors.push(`${key}: ${k} is a secret; set it with \`wrangler secret put\` or in .dev.vars, not here.`);
      else if (typeof v !== "string") errors.push(`${key}: ${k} must be a string.`);
      else vars[k] = v;
    }
  }
  return vars;
}

export function parseAccount(raw: unknown): { account: Account } | { errors: string[] } {
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) {
    return { errors: ["account.local.json must be a JSON object."] };
  }
  const o = raw as Record<string, unknown>;
  const errors: string[] = [];
  for (const k of Object.keys(o)) if (!KEYS.has(k)) errors.push(`Unknown key "${k}" (expected ${[...KEYS].join(", ")}).`);

  const ids: Record<string, string> = {};
  for (const k of ["productionDatabaseId", "previewDatabaseId"] as const) {
    const v = o[k];
    if (typeof v !== "string" || !UUID.test(v)) errors.push(`${k} must be a database ID (a UUID) printed by \`wrangler d1 create\`.`);
    else if (PLACEHOLDER.test(v)) errors.push(`${k} is an all-zero placeholder, not a real database ID.`);
    else ids[k] = v.toLowerCase();
  }
  if (ids.productionDatabaseId && ids.productionDatabaseId === ids.previewDatabaseId) {
    errors.push("productionDatabaseId and previewDatabaseId must be different databases.");
  }

  if (o.name !== undefined && (typeof o.name !== "string" || !/^[a-z0-9]([a-z0-9-]*[a-z0-9])?$/.test(o.name))) {
    errors.push("name (the Worker name) must be lower-case letters, digits and hyphens, not starting or ending with a hyphen.");
  }

  const vars = parseVars("vars", o.vars, errors);
  const productionVars = parseVars("productionVars", o.productionVars, errors);
  const previewVars = parseVars("previewVars", o.previewVars, errors);

  if (errors.length > 0) return { errors };
  return {
    account: {
      productionDatabaseId: ids.productionDatabaseId,
      previewDatabaseId: ids.previewDatabaseId,
      ...(o.name !== undefined ? { name: o.name as string } : {}),
      vars,
      ...(o.productionVars !== undefined ? { productionVars } : {}),
      ...(o.previewVars !== undefined ? { previewVars } : {}),
    },
  };
}

type Json = Record<string, any>;

function withDatabaseId(block: Json, where: string, id: string): void {
  const db = Array.isArray(block.d1_databases) ? block.d1_databases.find((d: Json) => d.binding === "DB") : undefined;
  if (!db) throw new Error(`wrangler.jsonc has no DB binding in ${where}.d1_databases.`);
  db.database_id = id;
}

/** The committed wrangler.jsonc with this account's ids (and vars) filled in. Does not change `template`. */
export function buildConfig(template: Json, account: Account): Json {
  const out: Json = structuredClone(template);
  const preview: Json | undefined = out.env?.preview;
  if (!preview) throw new Error("wrangler.jsonc has no env.preview block.");
  withDatabaseId(out, "the top-level", account.productionDatabaseId);
  withDatabaseId(preview, "env.preview", account.previewDatabaseId);
  if (account.name !== undefined) out.name = account.name;
  // vars is not inherited by env.preview, so each block gets the shared settings plus its own.
  const productionVars = { ...account.vars, ...account.productionVars };
  const previewVars = { ...account.vars, ...account.previewVars };
  if (Object.keys(productionVars).length > 0) out.vars = { ...out.vars, ...productionVars };
  if (Object.keys(previewVars).length > 0) preview.vars = { ...preview.vars, ...previewVars };
  return out;
}

/** The variable names (never values) written into each block, for the summary `npm run configure` prints. */
export function describeVars(account: Account): string {
  const production = Object.keys({ ...account.vars, ...account.productionVars });
  const preview = Object.keys({ ...account.vars, ...account.previewVars });
  if (production.length === 0 && preview.length === 0) return "no vars";
  return `vars (production): ${production.join(", ") || "none"}; vars (preview): ${preview.join(", ") || "none"}`;
}

/** Wrangler reads comments in .json files too, so the marker stays at the top. */
export function renderConfig(config: Json): string {
  return `// ${GENERATED_MARKER}\n${JSON.stringify(config, null, 2)}\n`;
}

export function isGenerated(text: string): boolean {
  return text.startsWith(`// ${GENERATED_MARKER}`);
}
